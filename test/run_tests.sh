#!/usr/bin/env bash
# Runs every Wokwi scenario in test/ against the current firmware build
# and writes a summary with the serial logs to test/RESULTS.md.
# Needs WOKWI_CLI_TOKEN and a build in .pio/build/esp32dev (pio run).
cd "$(dirname "$0")/.."
CLI="${WOKWI_CLI:-$HOME/.wokwi/bin/wokwi-cli.exe}"
pass=0; fail=0; rows=""; details=""
for s in test/*.yaml; do
  name=$(basename "$s" .yaml)
  title=$(sed -n 's/^name: //p' "$s")
  if "$CLI" --timeout 120000 --diagram-file test/diagram.json --scenario "$s" . > "test/$name.log" 2>&1; then
    result="PASS"; pass=$((pass+1))
  else
    result="FAIL"; fail=$((fail+1))
  fi
  echo "$result  $name"
  rows+="| \`$name\` | $title | **$result** |"$'\n'
  details+="<details><summary>$name – $result</summary>"$'\n\n```\n'"$(grep -v '^\s*$' "test/$name.log")"$'\n```\n\n</details>\n\n'
done
echo "$pass passed, $fail failed"

{
  echo "# Test results"
  echo
  echo "Generated by \`test/run_tests.sh\` (Wokwi CLI $("$CLI" --short-version 2>/dev/null))."
  echo
  echo "- Date: $(date '+%Y-%m-%d %H:%M')"
  echo "- Firmware commit: \`$(git rev-parse --short HEAD)\`$(git diff --quiet HEAD -- src || echo ' (with uncommitted changes in src/)')"
  echo "- Result: **$pass passed, $fail failed**"
  echo
  echo "| Scenario | Description | Result |"
  echo "|---|---|---|"
  printf '%s' "$rows"
  echo
  echo "Not covered by automation: ESP32 reset during an active stage, and several cycles in one run (each scenario starts a fresh simulation)."
  echo
  echo "## Serial logs"
  echo
  printf '%s' "$details"
} > test/RESULTS.md

[ "$fail" -eq 0 ]
